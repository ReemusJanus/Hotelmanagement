export const allowanceDDL = [
  'ALTER TABLE companies ADD COLUMN IF NOT EXISTS template_change_count INTEGER NOT NULL DEFAULT 0 CHECK (template_change_count >= 0)',
  "ALTER TABLE template_assignments ADD COLUMN IF NOT EXISTS source VARCHAR(12) NOT NULL DEFAULT 'superadmin' CHECK (source IN ('superadmin','admin','request')), ADD COLUMN IF NOT EXISTS request_id BIGINT NULL REFERENCES template_change_requests(id)",
  // The database itself guarantees at most one open request per tenant.
  "CREATE UNIQUE INDEX IF NOT EXISTS template_request_one_pending ON template_change_requests (company_id) WHERE status='pending'",
  'CREATE INDEX IF NOT EXISTS template_request_history ON template_change_requests (company_id,id)',
];

/** Idempotent. Runs inside the caller's master-schema transaction (search_path already set). */
export async function ensureTemplates(connection) {
  for (const [code, name, preview] of TEMPLATE_SEED) {
    await connection.query('INSERT INTO ui_templates (code,name,preview) VALUES (?,?,?::jsonb) ON CONFLICT (code) DO NOTHING', [code, name, JSON.stringify(preview)]);
  }
  await connection.query('ALTER TABLE companies ADD COLUMN IF NOT EXISTS template_id BIGINT REFERENCES ui_templates(id)');
  await connection.query("UPDATE companies SET template_id=(SELECT id FROM ui_templates WHERE code='classic') WHERE template_id IS NULL");
  // A default keeps inserts from an older backend valid during rollout or rollback.
  await connection.query(`DO $$ DECLARE classic BIGINT; BEGIN
    SELECT id INTO STRICT classic FROM ui_templates WHERE code='classic';
    EXECUTE format('ALTER TABLE companies ALTER COLUMN template_id SET DEFAULT %s, ALTER COLUMN template_id SET NOT NULL', classic);
  END $$`);
  for (const sql of allowanceDDL) await connection.query(sql);
  for (const sql of consoleDDL.filter((sql) => !sql.startsWith('CREATE TABLE'))) await connection.query(sql);
  await connection.query('CREATE INDEX IF NOT EXISTS companies_template ON companies (template_id)');
  await connection.query('CREATE INDEX IF NOT EXISTS template_assignment_history ON template_assignments (company_id,id)');
}

/** Resolves from the signed session's tenant only; callers must never pass a client-supplied database name. */
export async function tenantTemplate(pool, companyDatabase) {
  try {
    const [[row]] = await pool.query("SELECT t.id,t.code,t.version FROM companies c JOIN ui_templates t ON t.active AND (t.id=c.template_id OR t.code='classic') WHERE c.database_name=? ORDER BY (t.id=c.template_id) DESC LIMIT 1", [companyDatabase]);
    return row || { ...FALLBACK_TEMPLATE };
  } catch (error) {
    // Appearance must never stop a restaurant from signing in.
    console.error('Template lookup failed:', error.message);
    return { ...FALLBACK_TEMPLATE };
  }
}

const fail = (status, message) => { throw Object.assign(new Error(message), { status, reply: true }); };
const id = (value) => Number.isSafeInteger(value) && value > 0;
const clean = (value) => typeof value === 'string' ? value.trim() : '';

export function templateHandlers({ pool, broadcast, notify = async () => {} }) {
  /** One transaction, company row locked first in every path, so limits and approvals cannot race. */
  async function locked(res, where, value, work) {
    const conn = await pool.getConnection();
    try {
      await conn.beginTransaction();
      const [[company]] = await conn.query(`SELECT id,company_name "companyName",database_name "databaseName",email,template_id "templateId",template_change_count "changeCount" FROM companies WHERE ${where === 'id' ? 'id' : 'database_name'}=? FOR UPDATE`, [value]);
      if (!company) fail(404, 'Company not found');
      const result = await work(conn, company);
      await conn.commit();
      return { company, ...result };
    } catch (error) {
      await conn.rollback();
      if (error.code === '23505' && error.constraint === 'template_request_one_pending') error = Object.assign(new Error('A template request is already pending'), { status: 409, reply: true });
      if (!error.reply) throw error;
      res.status(error.status).json({ message: error.message });
      return null;
    } finally { conn.release(); }
  }
  const usable = async (conn, templateId) => {
    const [[template]] = await conn.query('SELECT id,code,name,version,active FROM ui_templates WHERE id=? FOR SHARE', [templateId]);
    if (!template) fail(404, 'Template not found');
    if (!template.active) fail(409, `${template.name} is inactive and cannot be used`);
    return template;
  };
  const master = async (conn, req) => {
    const [[actor]] = await conn.query('SELECT id,name FROM master_users WHERE id=? AND active=TRUE', [req.masterSession.id]);
    return actor || fail(403, 'An active Superadmin account is required');
  };
  const admin = async (conn, company, req) => {
    if (req.portalSession.role !== 'admin') fail(403, 'Admin access required');
    const [[actor]] = await conn.query("SELECT tenant_user_id id,name FROM company_users WHERE company_id=? AND tenant_user_id=? AND role='admin' AND active=TRUE", [company.id, req.portalSession.id]);
    return actor || fail(403, 'An active Admin account is required');
  };
  const apply = async (conn, company, template, actor, source, requestId = null) => {
    await conn.query('UPDATE companies SET template_id=? WHERE id=?', [template.id, company.id]);
    await conn.query('INSERT INTO template_assignments (company_id,company_name,previous_template_id,template_id,template_version,assigned_by,assigned_by_name,source,request_id) VALUES (?,?,?,?,?,?,?,?,?)', [company.id, company.companyName, company.templateId, template.id, template.version, actor.id, actor.name, source, requestId]);
  };
  const config = ({ id: templateId, code, version }) => ({ id: templateId, code, version });
  const announce = (company, template) => broadcast(company.databaseName, 'company.template', { template: config(template) });
  const requestColumns = 'q.id,q.company_id "companyId",q.company_name "companyName",c.name "currentName",t.id "templateId",t.code "templateCode",t.name "templateName",q.reason,q.status,q.requested_by_name "requestedBy",q.reviewed_by_name "reviewedBy",q.review_note "reviewNote",q.reviewed_at "reviewedAt",q.created_at "createdAt"';
  const requestFrom = 'FROM template_change_requests q JOIN ui_templates t ON t.id=q.requested_template_id JOIN ui_templates c ON c.id=q.current_template_id';

  return {
    async list(_req, res) {
      const [templates] = await pool.query('SELECT t.id,t.code,t.name,t.version,t.active,t.preview,t.created_at "createdAt",t.updated_at "updatedAt",(SELECT COUNT(*) FROM companies c WHERE c.template_id=t.id) "companyCount" FROM ui_templates t ORDER BY t.id');
      const [assignments] = await pool.query('SELECT c.id "companyId",c.company_name "companyName",c.hotel_id "hotelId",c.status,c.template_id "templateId",c.template_change_count "changeCount" FROM companies c ORDER BY c.company_name');
      const [history] = await pool.query(`SELECT a.id,a.company_id "companyId",a.company_name "companyName",p.name "previousName",t.name "templateName",a.template_version "templateVersion",a.assigned_by_name "assignedBy",a.source,a.created_at "createdAt" FROM template_assignments a JOIN ui_templates t ON t.id=a.template_id LEFT JOIN ui_templates p ON p.id=a.previous_template_id
        UNION ALL SELECT -r.id,r.company_id,r.company_name,r.previous_count||' used','Allowance reset','',r.reset_by_name,'reset',r.created_at FROM template_allowance_resets r ORDER BY "createdAt" DESC,id DESC LIMIT 100`);
      const [requests] = await pool.query(`SELECT ${requestColumns} ${requestFrom} ORDER BY (q.status='pending') DESC,q.id DESC LIMIT 100`);
      res.json({ templates, assignments, history, requests, changeLimit: CHANGE_LIMIT });
    },
    async assign(req, res) {
      const companyId = Number(req.params.id), templateId = req.body?.templateId;
      if (!id(companyId) || !id(templateId)) return res.status(400).json({ message: 'Choose a valid company and template' });
      const done = await locked(res, 'id', companyId, async (conn, company) => {
        const template = await usable(conn, templateId), expected = req.body.previousTemplateId;
        // Two Superadmins editing the same tenant must not silently overwrite each other.
        if (expected !== undefined && expected !== company.templateId) fail(409, 'This company’s template changed since you opened it. Refresh and try again.');
        if (company.templateId === template.id) return { template, changed: false };
        await apply(conn, company, template, await master(conn, req), 'superadmin');
        return { template, changed: true };
      });
      if (!done) return;
      // Open tenant screens refetch their configuration; Redis relays this to other instances.
      if (done.changed) announce(done.company, done.template); else res.locals.skipMutation = true;
      res.json({ ok: true, changed: done.changed, companyId, template: config(done.template) });
    },
    async resetAllowance(req, res) {
      const companyId = Number(req.params.id);
      if (!id(companyId)) return res.status(400).json({ message: 'Choose a valid company' });
      const done = await locked(res, 'id', companyId, async (conn, company) => {
        const actor = await master(conn, req);
        if (!company.changeCount) fail(409, 'This company has not used any changes');
        await conn.query('UPDATE companies SET template_change_count=0 WHERE id=?', [company.id]);
        await conn.query('INSERT INTO template_allowance_resets (company_id,company_name,previous_count,reset_by,reset_by_name) VALUES (?,?,?,?,?)', [company.id, company.companyName, company.changeCount, actor.id, actor.name]);
        return {};
      });
      if (!done) return;
      broadcast(done.company.databaseName, 'company.template-allowance');
      res.json({ ok: true, companyId, remaining: CHANGE_LIMIT });
    },
    async review(req, res) {
      const requestId = Number(req.params.id), decision = req.body?.decision, note = clean(req.body?.note);
      if (!id(requestId) || !['approved', 'rejected'].includes(decision) || note.length > 500) return res.status(400).json({ message: 'Choose approve or reject (notes up to 500 characters)' });
      const [[found]] = await pool.query('SELECT company_id "companyId" FROM template_change_requests WHERE id=?', [requestId]);
      if (!found?.companyId) return res.status(404).json({ message: 'Template request not found' });
      const done = await locked(res, 'id', found.companyId, async (conn, company) => {
        const actor = await master(conn, req);
        const [[request]] = await conn.query('SELECT status,requested_template_id "templateId" FROM template_change_requests WHERE id=? FOR UPDATE', [requestId]);
        if (request.status !== 'pending') fail(409, `This request was already ${request.status}`);
        let template, changed = false;
        if (decision === 'approved') {
          template = await usable(conn, request.templateId);
          changed = template.id !== company.templateId;
          if (changed) await apply(conn, company, template, actor, 'request', requestId);
        } else [[template]] = await conn.query('SELECT id,code,name,version FROM ui_templates WHERE id=?', [request.templateId]);
        await conn.query('UPDATE template_change_requests SET status=?,reviewed_by=?,reviewed_by_name=?,review_note=?,reviewed_at=NOW() WHERE id=?', [decision, actor.id, actor.name, note, requestId]);
        return { template, changed };
      });
      if (!done) return;
      if (done.changed) announce(done.company, done.template);
      broadcast(done.company.databaseName, 'company.template-request', { decision });
      if (done.company.email) await notify(done.company.email, 'email', `Template request ${decision}`, `Your request to use the ${done.template.name} template was ${decision}.${note ? ` Note: ${note}` : ''}`).catch(error => console.error('Template notice failed:', error.message));
      res.json({ ok: true, status: decision, changed: done.changed });
    },
    async pendingCount() {
      const [[row]] = await pool.query("SELECT COUNT(*) count FROM template_change_requests WHERE status='pending'");
      return row.count;
    },

    /* Tenant side: company always comes from the signed session. */
    async notice(session) {
      if (session.role !== 'admin') return null;
      const [[row]] = await pool.query("SELECT q.id,q.status,t.name \"templateName\" FROM template_change_requests q JOIN companies c ON c.id=q.company_id JOIN ui_templates t ON t.id=q.requested_template_id WHERE c.database_name=? AND q.status<>'pending' AND q.admin_seen_at IS NULL ORDER BY q.id DESC LIMIT 1", [session.companyDatabase]);
      return row || null;
    },
    async appearance(req, res) {
      if (req.portalSession.role !== 'admin') return res.status(403).json({ message: 'Admin access required' });
      const [[company]] = await pool.query('SELECT id,template_id "templateId",template_change_count "changeCount" FROM companies WHERE database_name=?', [req.portalSession.companyDatabase]);
      const [templates] = await pool.query('SELECT id,code,name,version,active,preview FROM ui_templates WHERE active OR id=? ORDER BY id', [company.templateId]);
      const [requests] = await pool.query(`SELECT ${requestColumns} ${requestFrom} WHERE q.company_id=? ORDER BY q.id DESC LIMIT 20`, [company.id]);
      res.json({ templates, currentTemplateId: company.templateId, changeLimit: CHANGE_LIMIT, changesUsed: company.changeCount, remaining: Math.max(0, CHANGE_LIMIT - company.changeCount), requests: requests.map(({ companyId, companyName, ...request }) => request) });
    },
    async change(req, res) {
      if (!id(req.body?.templateId)) return res.status(400).json({ message: 'Choose a valid template' });
      const done = await locked(res, 'database', req.portalSession.companyDatabase, async (conn, company) => {
        const actor = await admin(conn, company, req), template = await usable(conn, req.body.templateId), expected = req.body.previousTemplateId;
        if (expected !== undefined && expected !== company.templateId) fail(409, 'Your template changed since you opened this page. Refresh and try again.');
        if (company.templateId === template.id) return { template, changed: false, remaining: Math.max(0, CHANGE_LIMIT - company.changeCount) };
        if (company.changeCount >= CHANGE_LIMIT) fail(409, 'You have used all your template changes. Send a template change request instead.');
        await apply(conn, company, template, actor, 'admin');
        await conn.query('UPDATE companies SET template_change_count=template_change_count+1 WHERE id=?', [company.id]);
        return { template, changed: true, remaining: CHANGE_LIMIT - company.changeCount - 1 };
      });
      if (!done) return;
      if (done.changed) announce(done.company, done.template); else res.locals.skipMutation = true;
      res.json({ ok: true, changed: done.changed, remaining: done.remaining, template: config(done.template) });
    },
    async request(req, res) {
      const reason = clean(req.body?.reason);
      if (!id(req.body?.templateId) || reason.length < 5 || reason.length > 500) return res.status(400).json({ message: 'Choose a template and give a reason of 5 to 500 characters' });
      const done = await locked(res, 'database', req.portalSession.companyDatabase, async (conn, company) => {
        const actor = await admin(conn, company, req), template = await usable(conn, req.body.templateId);
        if (company.changeCount < CHANGE_LIMIT) fail(409, 'You can still change your template directly');
        if (template.id === company.templateId) fail(409, 'You already use this template');
        const [result] = await conn.query('INSERT INTO template_change_requests (company_id,company_name,current_template_id,requested_template_id,reason,requested_by,requested_by_name) VALUES (?,?,?,?,?,?,?)', [company.id, company.companyName, company.templateId, template.id, reason, actor.id, actor.name]);
        return { requestId: result.insertId };
      });
      if (!done) return;
      broadcast('master', 'template.request');
      res.status(201).json({ ok: true, id: done.requestId, status: 'pending' });
    },
    async seen(req, res) {
      if (req.portalSession.role !== 'admin') return res.status(403).json({ message: 'Admin access required' });
      await pool.query("UPDATE template_change_requests SET admin_seen_at=NOW() WHERE admin_seen_at IS NULL AND status<>'pending' AND company_id=(SELECT id FROM companies WHERE database_name=?)", [req.portalSession.companyDatabase]);
      res.locals.skipMutation = true;
      res.json({ ok: true });
    },
  };
}
